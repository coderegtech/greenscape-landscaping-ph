// Route coverage matrix (`pnpm docs:inventory`): every page.tsx in the three Next apps, matched against the screenshot
// manifest (pnpm docs:capture), the page documentation and the video scenes. Writes docs/overview/route-coverage.md.
// Drift check: `pnpm docs:inventory --check` exits 1 when a route has no documentation or the file is out of date.
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const APPS = { customer: 'apps/web/app', employee: 'apps/employee/app', admin: 'apps/admin/app' };
const OUT = 'docs/overview/route-coverage.md';
// Which documentation page covers a route: first match wins (portal, route prefix).
const DOCS = [
  ['customer', /^\/(auth|account|messages)/, 'docs/customer/account.md'],
  ['customer', /^\/(shop|cart|checkout|orders)/, 'docs/customer/shop.md'],
  ['customer', /^\/(services|projects|gallery)/, 'docs/customer/services-projects-gallery.md'],
  ['customer', /^\/$|^\/(about|stories|testimonials|faq|contact|quote|delivery-policy|privacy|design|\[slug\])/, 'docs/customer/site-pages.md'],
  ['employee', /./, 'docs/employee/portal.md'],
  ['admin', /^\/(login|mfa|password)$|^\/$|^\/(analytics|notifications)/, 'docs/admin/console.md'],
  ['admin', /^\/(orders|products|inventory|customers|quotations|messages|reports\/sales|settings\/delivery)/, 'docs/admin/commerce.md'],
  ['admin', /^\/cms/, 'docs/admin/cms.md'],
  ['admin', /^\/(employees|attendance|leave|reports\/attendance)/, 'docs/admin/hr.md'],
  ['admin', /^\/(users|system|settings|audit|assistant)/, 'docs/admin/system.md'],
];

const pages = (dir) => readdirSync(dir).flatMap((n) => {
  const p = join(dir, n);
  if (statSync(p).isDirectory()) return pages(p);
  return n === 'page.tsx' ? [p] : [];
});
const toRoute = (root, file) => {
  const parts = relative(root, file).split(sep).slice(0, -1).filter((s) => !/^\(.*\)$/.test(s));
  return `/${parts.join('/')}`;
};
const pattern = (route) => new RegExp(`^${route.replace(/\[[^\]]+\]/g, '[^/]+')}$`);

const manifest = existsSync('docs/assets/screenshots/manifest.json') ? JSON.parse(readFileSync('docs/assets/screenshots/manifest.json', 'utf8')).shots : [];
const scenes = existsSync('docs/video/scenes.json') ? JSON.parse(readFileSync('docs/video/scenes.json', 'utf8')).scenes.filter((s) => s.status !== 'blocked') : [];

const rows = [];
for (const [portal, root] of Object.entries(APPS)) {
  const files = pages(root).map((f) => f.split(sep).join('/')).sort(); // same order on every OS
  const routes = files.map((f) => toRoute(root, f));
  // A concrete path belongs to the most specific route it matches: /about is /about, not /[slug].
  const owner = (path) => routes.filter((r) => pattern(r).test(path)).sort((a, b) => (a.match(/\[/g) ?? []).length - (b.match(/\[/g) ?? []).length)[0];
  for (const [i, file] of files.entries()) {
    const route = routes[i];
    const shots = manifest.filter((s) => s.portal === portal && s.files.length && s.area !== 'errors' && owner(s.route.split('?')[0]) === route);
    const doc = DOCS.find(([p, r]) => p === portal && r.test(route))?.[2];
    const scene = scenes.find((s) => s.portal === portal && s.route && owner(s.route) === route);
    const auth = shots[0]?.auth ?? (/^\/(account|messages|cart|checkout|orders)/.test(route) && portal === 'customer' ? 'customer' : portal === 'customer' ? 'public' : route === '/login' ? 'public' : portal === 'employee' ? 'employee' : 'staff (permission)');
    const status = shots.length && doc && existsSync(doc) ? 'Documented, screenshot' : doc && existsSync(doc) ? 'Documented, no screenshot' : 'Missing documentation';
    rows.push({ portal, route, file, title: shots[0]?.title ?? '', auth, shot: shots[0]?.files[0], doc, scene: scene?.id, status });
  }
}

const cell = (s) => (s ?? '').replace(/\|/g, '\\|');
const rel = (p) => relative('docs/overview', p).split(sep).join('/');
let md = `# Route coverage\n\nGenerated by \`pnpm docs:inventory\` from the app folders, \`docs/assets/screenshots/manifest.json\` and \`docs/video/scenes.json\`. Do not edit by hand.\n\n`;
const count = (f) => rows.filter(f).length;
md += `| | Routes | With screenshot | Documented | In a video scene |\n|---|---|---|---|---|\n`;
for (const p of [...Object.keys(APPS), 'all']) {
  const f = (r) => p === 'all' || r.portal === p;
  md += `| ${p} | ${count(f)} | ${count((r) => f(r) && r.shot)} | ${count((r) => f(r) && r.doc && existsSync(r.doc))} | ${count((r) => f(r) && r.scene)} |\n`;
}
md += `\n"With screenshot" means Playwright loaded the route in the running app and captured it (\`pnpm docs:capture\`).\n`;
for (const p of Object.keys(APPS)) {
  md += `\n## ${p[0].toUpperCase()}${p.slice(1)}\n\n| Route | Page title | Access | Screenshot | Documentation | Video scene | Status |\n|---|---|---|---|---|---|---|\n`;
  for (const r of rows.filter((x) => x.portal === p)) {
    md += `| \`${cell(r.route)}\` | ${cell(r.title)} | ${r.auth} | ${r.shot ? `[image](${rel(r.shot)})` : '—'} | ${r.doc ? `[${r.doc.split('/').pop()}](${rel(r.doc)})` : '—'} | ${r.scene ?? '—'} | ${r.status} |\n`;
  }
}
const missingShots = manifest.filter((s) => !s.files.length);
if (missingShots.length) md += `\n## Not captured\n\n${missingShots.map((s) => `- \`${s.portal}${s.route}\`: ${s.note ?? 'no file'}`).join('\n')}\n`;

if (process.argv.includes('--check')) {
  const stale = !existsSync(OUT) || readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') !== md; // CRLF on Windows checkouts
  const undocumented = rows.filter((r) => r.status === 'Missing documentation');
  for (const r of undocumented) console.error(`undocumented: ${r.portal} ${r.route}`);
  if (stale) console.error(`${OUT} is out of date: run pnpm docs:inventory`);
  process.exit(stale || undocumented.length ? 1 : 0);
}
writeFileSync(OUT, md);
console.log(`${rows.length} routes, ${count((r) => r.shot)} with screenshots, ${count((r) => r.status === 'Missing documentation')} undocumented → ${OUT}`);

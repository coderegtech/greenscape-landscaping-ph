// Video production files from the one source of truth, docs/video/scenes.json (`pnpm docs:video:prepare`):
// master-storyboard.md (scene tables + estimated timeline per presentation), narration-script.md, shot-list.csv and
// a plain-text transcript. Timings are estimates from word count until real audio exists; re-run after recording.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const data = JSON.parse(readFileSync('docs/video/scenes.json', 'utf8'));
const byId = new Map(data.scenes.map((s) => [s.id, s]));
const wpm = data.voice.wordsPerMinute;
const words = (t) => t.split(/\s+/).filter(Boolean).length;
const speak = (s) => Math.ceil((words(s.narration) / wpm) * 60);
const seconds = (s) => speak(s) + 2; // a beat before the next scene
const clock = (t) => `${Math.floor(t / 60)}:${String(Math.round(t % 60)).padStart(2, '0')}`;
const img = (p) => (p ? `[image](${p.replace('docs/', '../')})` : '—');
const cell = (t) => t.replace(/\|/g, '\\|').replace(/\n/g, ' ');

let board = '# Master storyboard\n\nGenerated by `pnpm docs:video:prepare` from [`scenes.json`](scenes.json). Edit the JSON, then re-run. Durations are estimates (narration words at ' + wpm + ' wpm + 2 s); they become real once audio is generated.\n';
for (const p of data.presentations) {
  const scenes = p.sceneIds.map((id) => byId.get(id));
  const total = scenes.reduce((n, s) => n + seconds(s), 0);
  const fit = total >= p.targetSeconds[0] && total <= p.targetSeconds[1] ? 'within target' : total < p.targetSeconds[0] ? 'short of target: allow longer screen holds' : 'over target: trim';
  board += `\n## ${p.title}\n\nTarget ${clock(p.targetSeconds[0])}–${clock(p.targetSeconds[1])} · narration estimate **${clock(total)}** (${fit}) · status **${p.status}** · export ${p.export ?? 'not produced'}\n\n`;
  board += '| Scene | Start | Duration | Portal | Page | Feature | Screen action | Visual direction | Screenshot | Recording | Status |\n|---|---|---|---|---|---|---|---|---|---|---|\n';
  let t = 0;
  for (const s of scenes) {
    board += `| ${s.id} ${cell(s.title)} | ${clock(t)} | ${seconds(s)} s | ${s.portal} | ${s.route ? `\`${s.route}\`` : '—'} | ${cell(s.feature)} | ${cell(s.screenAction.join('; '))} | ${cell(s.visualDirection.join('; '))} | ${img(s.screenshot)} | ${s.recording ?? 'missing'} | ${s.status} |\n`;
    t += seconds(s);
  }
}
const blocked = data.scenes.filter((s) => s.status === 'blocked');
board += `\n## Blocked scenes\n\n| Scene | Why | Instead |\n|---|---|---|\n${blocked.map((s) => `| ${s.id} ${s.title} | ${cell(s.blockedReason ?? '')} | left out of every presentation |`).join('\n')}\n`;

let script = '# Narration script\n\nGenerated by `pnpm docs:video:prepare` from [`scenes.json`](scenes.json). Voice: ' + data.voice.style + '. The caption text is the narration, split at sentences.\n';
for (const s of data.scenes) {
  script += `\n## ${s.id} · ${s.title}\n\n- **Portal / page:** ${s.portal}${s.route ? ` · \`${s.route}\`` : ''}\n- **Speaking time:** ~${speak(s)} s (${words(s.narration)} words)\n- **Tone:** ${s.tone ?? 'Neutral'}\n${s.pronunciation ? `- **Pronunciation:** ${s.pronunciation}\n` : ''}- **Matching action:** ${s.screenAction.join('; ')}\n- **Status:** ${s.status}${s.blockedReason ? ` — ${s.blockedReason}` : ''}\n\n> ${s.narration}\n\nCaptions:\n${s.narration.split(/(?<=[.!?])\s+/).map((c) => `1. ${c}`).join('\n')}\n`;
}

const csv = (v) => `"${String(v ?? '').replace(/"/g, '""')}"`;
const rows = [['presentation', 'scene', 'title', 'portal', 'route', 'estimated_seconds', 'screen_action', 'visual_direction', 'screenshot', 'recording_file', 'audio_file', 'status']];
for (const p of data.presentations) for (const id of p.sceneIds) {
  const s = byId.get(id);
  rows.push([p.id, s.id, s.title, s.portal, s.route, seconds(s), s.screenAction.join('; '), s.visualDirection.join('; '), s.screenshot, s.recording ?? `docs/video/assets/recordings/${s.id}.mp4`, s.audio ?? `docs/video/assets/audio/${s.id}.mp3`, s.status]);
}

const transcript = data.presentations.map((p) => `${p.title}\n\n${p.sceneIds.map((id) => byId.get(id).narration).join('\n\n')}\n`).join('\n\n');

writeFileSync('docs/video/master-storyboard.md', board);
writeFileSync('docs/video/narration-script.md', script);
writeFileSync('docs/video/shot-list.csv', `${rows.map((r) => r.map(csv).join(',')).join('\n')}\n`);
mkdirSync('docs/video/assets/captions', { recursive: true });
writeFileSync('docs/video/assets/captions/transcript.txt', transcript);
console.log(`${data.scenes.length} scenes, ${data.presentations.length} presentations → master-storyboard.md, narration-script.md, shot-list.csv, assets/captions/transcript.txt`);

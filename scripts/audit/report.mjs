// Turns docs/audit/raw/{crawl,lighthouse}.json into generated sections of the audit markdown.
// Writes docs/audit/{routes,performance,accessibility,api-endpoints}.md (generated parts) — rerun after crawling.
import fs from 'node:fs';
import path from 'node:path';

const D = path.resolve(import.meta.dirname, '../../docs/audit');
const crawl = JSON.parse(fs.readFileSync(path.join(D, 'raw/crawl.json'), 'utf8'));
const lhPath = path.join(D, 'raw/lighthouse.json');
const lh = fs.existsSync(lhPath) ? JSON.parse(fs.readFileSync(lhPath, 'utf8')) : null;
const P = crawl.pages;
const rel = (u) => u.replace(crawl.origin, '') || '/';
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const head = (t) => `# ${t}\n\n_Generated by \`scripts/audit/report.mjs\` from a Playwright crawl on ${crawl.crawledAt.slice(0, 10)} (${P.length} pages × desktop 1440 / mobile 390)._\n\n`;

// ── routes.md
{
  let md = head('Route Inventory');
  md += '| # | Path | Status | Title | H1 | Meta description | Screenshots |\n|---|---|---|---|---|---|---|\n';
  P.forEach(({ desktop: d, mobile: m }, i) => {
    const h1 = (d.headings || []).filter((h) => h.startsWith('H1')).map((h) => h.slice(4)).join(' / ') || '—';
    md += `| ${i + 1} | \`${esc(rel(d.url))}\` | ${d.status}${d.error ? ' ⚠' : ''} | ${esc(d.title)} | ${esc(h1)} | ${d.metaDescription ? '✓' : '✗ missing'} | ${d.screenshot ? `[desktop](${d.screenshot}) · [mobile](${m.screenshot})` : '—'} |\n`;
  });
  const ext = new Map();
  for (const { desktop: d } of P) for (const l of d.links || []) if (!l.href.startsWith(crawl.origin) && /^https?:/.test(l.href)) ext.set(l.href, l.text);
  md += `\n## External links\n\n${[...ext.keys()].sort().map((h) => `- ${h}`).join('\n')}\n`;
  const nonHttp = new Set();
  for (const { desktop: d } of P) for (const l of d.links || []) if (/^(tel|mailto):/.test(l.href)) nonHttp.add(l.href);
  md += `\n## tel/mailto\n\n${[...nonHttp].map((h) => `- ${h}`).join('\n') || '- none'}\n`;
  md += `\n## Discovered but not crawled (limit reached)\n\n${crawl.unvisited.length ? crawl.unvisited.map((u) => `- ${rel(u)}`).join('\n') : '- none'}\n`;
  md += '\n## Per-page headings\n\n';
  for (const { desktop: d } of P) md += `<details><summary><code>${rel(d.url)}</code></summary>\n\n${(d.headings || []).map((h) => `- ${esc(h)}`).join('\n')}\n\n</details>\n`;
  fs.writeFileSync(path.join(D, 'routes.md'), md);
}

// ── performance.md
{
  let md = head('Performance Baseline');
  if (lh) {
    md += `## Lighthouse (${lh.ranAt.slice(0, 10)}, visitor tracker + GA blocked)\n\n| Page | Preset | Perf | A11y | Best pr. | SEO | LCP | FCP | TBT | CLS | Weight |\n|---|---|---|---|---|---|---|---|---|---|---|\n`;
    for (const r of lh.results) {
      if (r.error) { md += `| \`${r.url}\` | ${r.preset} | error: ${esc(r.error)} |||||||||\n`; continue; }
      const s = r.scores;
      md += `| \`${r.url}\` | ${r.preset} | ${s.performance} | ${s.accessibility} | ${s['best-practices']} | ${s.seo} | ${r.lcp} | ${r.fcp} | ${r.tbt} | ${r.cls} | ${r.weight} |\n`;
    }
    const opp = new Map();
    for (const r of lh.results) for (const o of r.opportunities || []) { const k = o.split(' — ')[0]; opp.set(k, (opp.get(k) || 0) + 1); }
    md += `\n### Recurring opportunities (count of page×preset runs)\n\n${[...opp].sort((a, b) => b[1] - a[1]).map(([k, n]) => `- ${k} — ${n}`).join('\n')}\n`;
  }
  md += '\n## Field-style timings from the crawl (unthrottled, this machine → Fastly SIN)\n\n_Transfer/Image KB **undercount**: Firebase Storage images are cross-origin without `Timing-Allow-Origin`, so the browser reports 0 bytes for them. Use Lighthouse "Weight" above for real page weight. LCP here is unthrottled and includes the Firestore round-trip before content exists._\n\n| Path | Viewport | TTFB ms | DCL ms | Load ms | LCP ms | CLS | Requests | Transfer KB | Image KB | DOM nodes | H-overflow |\n|---|---|---|---|---|---|---|---|---|---|---|---|\n';
  for (const pg of P) for (const v of ['desktop', 'mobile']) {
    const d = pg[v]; const t = d.timing || {};
    md += `| \`${esc(rel(d.url))}\` | ${v} | ${t.ttfb ?? ''} | ${t.dcl ?? ''} | ${t.load ?? ''} | ${t.lcp ?? ''} | ${t.cls ?? ''} | ${t.requests ?? ''} | ${t.transferKB ?? ''} | ${t.imageKB ?? ''} | ${t.domNodes ?? ''} | ${d.horizontalOverflow ? '⚠ yes' : 'no'} |\n`;
  }
  // big images: natural size much larger than displayed
  const big = [];
  for (const pg of P) for (const i of pg.desktop.images || []) if (i.w > 0 && i.dw > 0 && i.w > i.dw * 2.5 && i.w > 1200) big.push(`${rel(pg.desktop.url)} — ${i.src.split('?')[0].slice(-80)} (${i.w}px shown at ${i.dw}px)`);
  md += `\n## Oversized images (natural width > 2.5× displayed, desktop)\n\n${[...new Set(big)].slice(0, 60).map((b) => `- ${esc(b)}`).join('\n') || '- none'}\n`;
  const fmt = new Map();
  for (const pg of P) for (const i of pg.desktop.images || []) { const m = (i.src.split('?')[0].match(/\.(\w{3,4})$/) || [, 'other'])[1].toLowerCase(); fmt.set(m, (fmt.get(m) || 0) + 1); }
  md += `\n## Image formats (desktop, all pages)\n\n${[...fmt].map(([k, n]) => `- ${k}: ${n}`).join('\n')}\n`;
  const lazy = P.reduce((a, pg) => { for (const i of pg.desktop.images || []) a[i.loading === 'lazy' ? 'lazy' : 'eager']++; return a; }, { lazy: 0, eager: 0 });
  md += `\nLazy-loaded: ${lazy.lazy}, eager: ${lazy.eager}\n`;
  fs.writeFileSync(path.join(D, 'performance.md'), md);
}

// ── accessibility.md
{
  let md = head('Accessibility Baseline');
  const agg = new Map();
  for (const pg of P) for (const v of pg.desktop.axe || []) {
    const a = agg.get(v.id) || { ...v, pages: 0, nodes: 0 }; a.pages++; a.nodes += v.count || 0; agg.set(v.id, a);
  }
  md += '## axe-core WCAG 2.0/2.1 A+AA violations (desktop)\n\n| Rule | Impact | Pages | Nodes | Description | Example selector |\n|---|---|---|---|---|---|\n';
  for (const a of [...agg.values()].sort((x, y) => y.pages - x.pages)) md += `| \`${a.id}\` | ${a.impact} | ${a.pages} | ${a.nodes} | ${esc(a.help)} | \`${esc(a.sample)}\` |\n`;
  if (lh) {
    const f = new Map();
    for (const r of lh.results) for (const t of r.failingA11y || []) f.set(t, (f.get(t) || 0) + 1);
    md += `\n## Lighthouse accessibility audits failing (of ${lh.results.length} page×preset runs)\n\n| Audit | Runs |\n|---|---|\n${[...f].sort((a, b) => b[1] - a[1]).map(([t, n]) => `| ${esc(t)} | ${n} |`).join('\n')}\n\nScores: ${lh.results.filter((r) => !r.error).map((r) => `\`${r.url}\` ${r.preset} ${r.scores.accessibility}`).join(' · ')}\n`;
  }
  md += '\n## Per page\n\n| Path | lang | Violations (rule×nodes) | Images without alt | Unlabelled form fields | Unnamed buttons | Mobile H-overflow |\n|---|---|---|---|---|---|---|\n';
  for (const { desktop: d, mobile: m } of P) {
    const noAlt = (d.images || []).filter((i) => i.alt === null).length;
    const unl = (d.forms || []).flatMap((f) => f.fields).filter((f) => !f.labelled).length;
    const unb = (d.buttons || []).filter((b) => b === '(unnamed)').length;
    md += `| \`${esc(rel(d.url))}\` | ${d.lang || '✗'} | ${(d.axe || []).map((v) => `${v.id}×${v.count}`).join(', ') || '—'} | ${noAlt} | ${unl} | ${unb} | ${m.horizontalOverflow ? '⚠' : '—'} |\n`;
  }
  fs.writeFileSync(path.join(D, 'accessibility.md'), md);
}

// ── api-endpoints.md (observed network)
{
  let md = head('Observed API / Network Endpoints');
  md += 'The site has **no first-party API**. All dynamic data comes from Firebase SDK calls made in the browser.\n\n';
  const calls = new Map();
  for (const pg of P) for (const v of ['desktop', 'mobile']) for (const c of pg[v].apiCalls || []) { const k = c.replace(/(channel)\?.*/, '$1'); calls.set(k, (calls.get(k) || new Set()).add(rel(pg[v].url))); }
  md += '| Request | Seen on (pages) |\n|---|---|\n';
  for (const [k, s] of [...calls].sort()) md += `| \`${esc(k)}\` | ${s.size} |\n`;
  const errs = new Map();
  for (const pg of P) for (const v of ['desktop', 'mobile']) for (const e of [...(pg[v].badStatus || []), ...(pg[v].failedRequests || [])]) if (!/ERR_ABORTED https:\/\/firestore/.test(e)) errs.set(e.slice(0, 200), (errs.get(e.slice(0, 200)) || 0) + 1);
  md += `\n## Failed / 4xx-5xx requests\n\n_Firestore \`Listen/channel\` ERR_ABORTED entries are omitted: they are long-poll connections cut when the crawler closes each page._\n\n${[...errs].map(([e, n]) => `- \`${esc(e)}\` ×${n}`).join('\n') || '- none'}\n`;
  const cons = new Map();
  for (const pg of P) for (const v of ['desktop', 'mobile']) for (const e of pg[v].console || []) cons.set(e.slice(0, 220), (cons.get(e.slice(0, 220)) || 0) + 1);
  md += `\n## Console errors / warnings\n\n_\`net::ERR_FAILED\` lines are the crawler's own blocking of the visitor tracker, GA and Firestore writes, not site faults. WebGL/adapter warnings come from headless Chromium._\n\n${[...cons].sort((a, b) => b[1] - a[1]).map(([e, n]) => `- ×${n} \`${esc(e)}\``).join('\n') || '- none'}\n`;
  const third = new Set();
  for (const pg of P) for (const s of [...(pg.desktop.scripts || []), ...(pg.desktop.stylesheets || [])]) if (!s.startsWith(crawl.origin)) third.add(s.split('?')[0]);
  md += `\n## Third-party scripts & styles\n\n${[...third].sort().map((s) => `- ${s}`).join('\n')}\n`;
  const forms = [];
  for (const { desktop: d } of P) for (const f of d.forms || []) forms.push({ page: rel(d.url), ...f });
  md += `\n## Forms (recorded from DOM, not submitted)\n\n`;
  const seenF = new Set();
  for (const f of forms) {
    const sig = f.fields.map((x) => x.name).join(',');
    if (seenF.has(sig)) continue; seenF.add(sig);
    md += `### \`${f.id || '(no id)'}\` on \`${f.page}\`\n\n| Field | Type | Required | Labelled | Options |\n|---|---|---|---|---|\n${f.fields.map((x) => `| ${esc(x.name || x.placeholder)} | ${x.type} | ${x.required ? 'yes' : ''} | ${x.labelled ? 'yes' : '✗'} | ${esc((x.options || []).join(', '))} |`).join('\n')}\n\n`;
  }
  fs.writeFileSync(path.join(D, 'api-endpoints.md'), md);
}
